-- V20: SLA가 처리 흐름과 맞도록.
-- handover_at: 지금 담당(통신사 · 교육지원청 · 교육청)이 넘겨받은 시각. SLA 접수 · 현장 도착은 이때부터 잰다 (없으면 신청 시각).
alter table as_requests add column handover_at timestamp(6);
-- visit_recorded: 현장 도착을 실제로 기록했는가 (QR · 도착 기록 · 보고서의 방문일시). false면 예정 시각으로 채운 값이라 SLA에 쓰지 않는다.
-- null = 이 컬럼 전의 자료. 도착 기록(ARRIVE) 이력이 있는 건은 기록된 것으로 본다.
alter table as_requests add column visit_recorded boolean;
update as_requests set visit_recorded = true
 where asvc_sn in (select asvc_sn from as_histories where action = 'ARRIVE');

-- 담당 구간: 신고가 담당을 옮길 때마다 한 줄. 담당마다 자기 접수 시간으로 SLA를 판정한다 (넘긴 뒤 위반을 지우거나 새로 만들지 않도록).
create table as_handovers (
    handover_id bigint generated by default as identity,
    org_id bigint not null,
    asvc_sn bigint not null,
    handler_type varchar(10) not null,   -- VENDOR · REGION · PROVINCE
    vendor_id bigint,
    user_id bigint,
    start_at timestamp(6) not null,      -- 이 담당이 넘겨받은 시각 (첫 구간은 신청 시각)
    received_at timestamp(6),            -- 이 담당이 접수한 시각
    end_at timestamp(6),                 -- 다음 담당에게 넘긴 시각 (null = 지금 담당)
    primary key (handover_id)
);
create index ix_as_handovers_sn on as_handovers (asvc_sn);
create index ix_as_handovers_org on as_handovers (org_id, start_at);
