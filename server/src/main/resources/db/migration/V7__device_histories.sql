-- V7: 장비 위치 변경 기록 (무선장비·스쿨넷 장비의 설치위치가 바뀔 때마다 한 줄). DeviceHistory 엔티티.
create table device_histories (
    history_id bigint generated by default as identity,
    device_id bigint,
    org_id bigint,
    worker_id bigint,
    created_at timestamp(6),
    action_type varchar(20),
    worker_name varchar(50),
    from_place varchar(255),
    to_place varchar(255),
    primary key (history_id)
);

create index idx_device_histories_device on device_histories (device_id, history_id);
