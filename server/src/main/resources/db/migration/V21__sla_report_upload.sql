-- 스쿨넷 SLA 결과: 통신사(업체) · 연월마다 한 건. 반려되면 다시 올려 같은 줄을 고친다.
create table sla_reports (
    report_id bigint generated by default as identity,
    org_id bigint not null,
    vendor_id bigint not null,
    report_year integer not null,
    report_month integer not null,
    note varchar(1000),
    file_ids varchar(500) not null,         -- 첨부 파일 id (쉼표), 한글(.hwp · .hwpx) · 엑셀(.xlsx · .xls)
    status varchar(10) not null,            -- SUBMITTED 승인 대기 · APPROVED 승인 · REJECTED 반려
    reject_reason varchar(1000),
    submitted_by bigint,
    submitted_at timestamp(6) not null,
    reviewed_by bigint,
    reviewed_at timestamp(6),
    primary key (report_id),
    constraint uk_sla_reports unique (org_id, vendor_id, report_year, report_month)
);
create index ix_sla_reports_org on sla_reports (org_id, report_year, report_month);
