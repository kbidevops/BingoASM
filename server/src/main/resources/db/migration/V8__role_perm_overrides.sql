-- V8: 역할 권한 관리 (교육청별). 역할 기본값(Roles.ROLE_PERMS)에서 켜고 끈 메뉴·처리 기능 권한. RolePermOverride 엔티티.
-- effect: G = 역할에 없는 권한을 켬, D = 역할에 있는 권한을 끔.
create table role_perm_overrides (
    override_id bigint generated by default as identity,
    org_id bigint not null,
    role_code varchar(30) not null,
    perm_code varchar(40) not null,
    effect varchar(1) not null,
    updated_at timestamp(6),
    updated_by bigint,
    primary key (override_id),
    constraint uk_role_perm_overrides unique (org_id, role_code, perm_code)
);
