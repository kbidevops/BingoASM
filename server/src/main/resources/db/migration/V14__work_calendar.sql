-- V14: 근무 시간 달력. 지연 알림을 근무 시간으로 셀 때 쓴다 (교육청마다 한 줄, 없으면 월~금 09:00~18:00).
create table work_calendars (
    org_id bigint not null,
    work_days varchar(20) not null,      -- ISO 요일 1(월) ~ 7(일), 쉼표로: "1,2,3,4,5"
    start_time varchar(5) not null,      -- "09:00"
    end_time varchar(5) not null,        -- "18:00"
    updated_at timestamp(6),
    updated_by bigint,
    primary key (org_id)
);

-- 휴일 (공휴일 · 재량휴업일 등): 근무 요일이어도 근무 시간으로 세지 않는다.
create table holidays (
    holiday_id bigint generated by default as identity,
    org_id bigint not null,
    holiday_date date not null,
    name varchar(50),
    primary key (holiday_id),
    constraint uk_holidays unique (org_id, holiday_date)
);

-- 지연 알림 기준마다: 근무 시간으로 셀지(true) 24시간으로 셀지(false). 스쿨넷은 회선 관제라 24시간이 기본.
alter table as_alert_rules add column business_hours boolean default true not null;
update as_alert_rules set business_hours = false where rcept_ty = 'S';
