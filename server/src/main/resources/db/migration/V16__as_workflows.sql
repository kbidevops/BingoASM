-- V16: AS 처리 흐름 (교육청 · AS 유형마다 한 줄). 없으면 코드의 기본값 (WorkflowService.DEFAULTS).
-- 상태(신청완료 → 접수완료 → 처리완료 / 반려)는 고정이고, 단계마다 누가 · 꼭 하는지를 고른다.
create table as_workflows (
    workflow_id bigint generated by default as identity,
    org_id bigint not null,
    rcept_ty varchar(1) not null,
    first_receiver varchar(10) not null,   -- VENDOR 업체로 바로 · REGION 교육지원청이 먼저 확인
    device_link varchar(12) not null,      -- REQUIRED 필수 · RECOMMENDED 권장(할 일) · OPTIONAL 선택 · NONE 사용 안 함
    vendor_source varchar(10) not null,    -- SCHOOL 학교 배정 업체 · DEVICE 장비의 유지보수 업체
    engineer_assign varchar(10) not null,  -- ADMIN 업체 관리자가 지정 · AUTO 학교 기본 담당 기사 자동
    office_handling boolean not null,      -- 교육지원청 · 교육청 직접 처리 (처리 담당 지정)
    arrival_required boolean not null,     -- 처리 보고서 전에 현장 도착 기록 필수 (업체 처리 건)
    evaluation boolean not null,           -- 만족도 평가
    updated_at timestamp(6),
    updated_by bigint,
    primary key (workflow_id),
    constraint uk_as_workflows unique (org_id, rcept_ty)
);
