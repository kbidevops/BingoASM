-- V13: AS 지연 알림 (에스컬레이션).
-- 교육청 · 유형별 기준 (없으면 기본값: 정보기기 · 스마트기기 8시간/24시간/2시간, 무선망 4시간/8시간/1시간, 스쿨넷 30분/1시간/30분).
create table as_alert_rules (
    rule_id bigint generated by default as identity,
    org_id bigint not null,
    rcept_ty varchar(1) not null,
    receive_min integer not null,
    escalate_min integer not null,
    visit_grace_min integer not null,
    enabled boolean default true not null,
    updated_at timestamp(6),
    updated_by bigint,
    primary key (rule_id),
    constraint uk_as_alert_rules unique (org_id, rcept_ty)
);

-- 보낸 단계: 0 없음 · 1 접수 지연(업체) · 2 에스컬레이션(교육지원청). 방문 지연은 알린 방문예정일시를 남겨, 일정을 바꾸면 다시 알린다.
alter table as_requests add column receive_alert_level integer default 0 not null;
alter table as_requests add column visit_alert_for timestamp(6);
